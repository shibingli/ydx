// func indexByteAVX2(data []byte, start int, c byte) int
TEXT ·indexByteAVX2(SB), NOSPLIT, $0-48
	MOVQ data_base+0(FP), AX
	MOVQ data_len+8(FP), BX
	MOVQ start+24(FP), R8
	MOVBLZX c+32(FP), R12
	MOVD R12, X1
	VPBROADCASTB X1, Y1
loop:
	MOVQ BX, R9
	SUBQ R8, R9
	CMPQ R9, $32
	JL tail
	LEAQ (AX)(R8*1), R10
	VMOVDQU (R10), Y0
	VPCMPEQB Y1, Y0, Y5
	VPMOVMSKB Y5, R11
	TESTL R11, R11
	JNE hit
	ADDQ $32, R8
	JMP loop
hit:
	BSFL R11, R11
	ADDQ R11, R8
	VZEROUPPER
	MOVQ R8, ret+40(FP)
	RET
tail:
	CMPQ R8, BX
	JGE notfound
	MOVBLZX (AX)(R8*1), R11
	CMPB R11, R12
	JE found
	INCQ R8
	JMP tail
found:
	VZEROUPPER
	MOVQ R8, ret+40(FP)
	RET
notfound:
	VZEROUPPER
	MOVQ $-1, R8
	MOVQ R8, ret+40(FP)
	RET

